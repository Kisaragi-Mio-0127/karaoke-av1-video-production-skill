def _summary(item: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in item.items() if key != "media"}


def main(argv: list[str] | None = None) -> int:
    args = make_parser().parse_args(argv)
    try:
        album: AlbumManifest = render_core.load_album_manifest(
            _resolve_path(args.manifest),
            require_five_tracks=not args.allow_partial_manifest,
        )
        root = _resolve_path(args.root) if args.root else album.deliverable_dir.resolve()
        tracks = render_core.select_tracks(album, args.songs)
        profiles = render_core.select_profiles(args.profiles)
        visual_styles = render_core.select_visual_styles(args.visual_style)
        if args.single_track and (len(tracks) != 1 or len(profiles) != 1):
            raise ValueError(
                "--single-track requires exactly one selected song and one profile"
            )
        preview_script = _resolve_path(args.preview_script)
        if not args.report_only and not preview_script.is_file():
            raise FileNotFoundError(f"preview script does not exist: {preview_script}")
        ffmpeg = _resolve_path(args.ffmpeg) if args.ffmpeg else None
        tasks = configure_av1_tasks(
            render_core.plan_tasks(
                album,
                root=root,
                tracks=tracks,
                profiles=profiles,
                visual_styles=visual_styles,
                timing_dir=_resolve_path(args.timing_dir) if args.timing_dir else None,
                artwork_root=_resolve_path(args.artwork_dir)
                if args.artwork_dir
                else None,
                fonts_dir=_resolve_path(args.fonts_dir) if args.fonts_dir else None,
                font_file=_resolve_path(args.font_file) if args.font_file else None,
            ),
            root=root,
        )
        if args.single_track and len(tasks) != len(visual_styles):
            raise ValueError(
                f"--single-track produced {len(tasks)} tasks; "
                f"expected {len(visual_styles)} style task(s)"
            )
        pronunciation_validation = validate_editable_pronunciation_sources(
            tasks,
            mode=args.pronunciation_validation,
        )
        vinyl_assets = validate_current_vinyl_assets(tasks)
        wide_compositions = validate_current_wide_compositions(tasks)
        complete_track_selection = len(tracks) == len(album.tracks)
        if args.report_only and not complete_track_selection:
            raise ValueError("--report-only requires the complete manifest selection")
        if args.refresh_existing_reports and not args.report_only:
            raise ValueError("--refresh-existing-reports requires --report-only")
        if args.refresh_existing_reports and args.full_decode:
            raise ValueError(
                "--refresh-existing-reports does not permit --full-decode"
            )
        if args.full_decode and args.skip_full_decode_reason:
            raise ValueError(
                "--full-decode and --skip-full-decode-reason are mutually exclusive"
            )

        if args.report_only:
            if args.refresh_existing_reports:
                results = refresh_existing_reports(
                    tasks,
                    ffmpeg=ffmpeg,
                    av1_cq=args.av1_cq,
                    lossless_companion=args.lossless_companion,
                )
            else:
                results = collect_existing_results(
                    tasks,
                    ffmpeg=ffmpeg,
                    av1_cq=args.av1_cq,
                    full_decode=args.full_decode,
                    lossless_companion=args.lossless_companion,
                )
        else:
            results = []
            task_groups = group_tasks_for_render(tasks)

            def render_group(
                group: Sequence[render_core.RenderTask],
            ) -> list[dict[str, Any]]:
                return [
                    render_one(
                        task,
                        preview_script=preview_script,
                        ffmpeg=ffmpeg,
                        av1_cq=args.av1_cq,
                        pronunciation_validation=args.pronunciation_validation,
                        vinyl_motion=args.vinyl_motion,
                        lossless_companion=args.lossless_companion,
                        full_decode=args.full_decode,
                        singer_colors=args.singer_color,
                    )
                    for task in group
                ]

            with ThreadPoolExecutor(
                max_workers=min(args.jobs, len(task_groups))
            ) as executor:
                futures = {
                    executor.submit(render_group, group): group
                    for group in task_groups
                }
                for future in as_completed(futures):
                    for item in future.result():
                        results.append(item)
                        print(json.dumps(_summary(item), ensure_ascii=False), flush=True)

        aggregate_report: Path | None = None
        if complete_track_selection:
            aggregate_report = root / "validation" / AV1_REPORT_NAME
            write_json_atomically(
                aggregate_report,
                build_av1_420_report(
                    results,
                    root=root,
                    av1_cq=args.av1_cq,
                    full_decode=args.full_decode,
                    full_decode_exception_reason=args.skip_full_decode_reason,
                    profiles=profiles,
                    visual_styles=visual_styles,
                    expected_song_count=len(tracks),
                ),
            )
        print(
            json.dumps(
                {
                    "status": "pass",
                    "release_decision": "verified",
                    "task_count": len(results),
                    "profiles": list(profiles),
                    "visual_styles": list(visual_styles),
                    "songs": [str(track.song_id) for track in tracks],
                    "pixel_format": "yuv420p",
                    "pronunciation_validation": pronunciation_validation,
                    "vinyl_motion": args.vinyl_motion,
                    "vinyl_assets": vinyl_assets,
                    "wide_compositions": wide_compositions,
                    "aggregate_report": str(aggregate_report)
                    if aggregate_report
                    else None,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
        return 0
    except Exception as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
