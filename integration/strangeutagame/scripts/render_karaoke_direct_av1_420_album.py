def group_tasks_for_render(
    tasks: Iterable[render_core.RenderTask],
) -> tuple[tuple[render_core.RenderTask, ...], ...]:
    """Serialize styles sharing one song/profile ASS while preserving parallel groups."""

    groups: dict[tuple[str, str], list[render_core.RenderTask]] = {}
    for task in tasks:
        key = (task.profile, str(task.track.song_id))
        groups.setdefault(key, []).append(task)
    return tuple(tuple(group) for group in groups.values())


def lossless_companion_policy(
    audio_path: Path,
    *,
    requested: bool = False,
) -> dict[str, Any]:
    """Request a companion only when preview can prove a lossless source codec."""

    suffix = audio_path.suffix.casefold()
    if not requested:
        return {
            "status": "omitted",
            "requested": False,
            "performed": False,
            "reason": "lossless-companion-not-requested",
            "source_suffix": suffix,
        }
    if suffix == ".flac":
        return {
            "status": "requested",
            "requested": True,
            "performed": False,
            "reason": "flac-source-explicit-lossless-companion-request",
            "source_suffix": suffix,
        }
    if suffix in {".wav", ".wave"}:
        return {
            "status": "requested",
            "requested": True,
            "performed": False,
            "reason": "wav-source-explicit-request-requires-pcm-codec-probe",
            "source_suffix": suffix,
        }
    raise DirectAV1420RenderError(
        "lossless source is required when --lossless-companion is requested; "
        f"got {audio_path}"
    )


def build_preview_command(
    task: render_core.RenderTask,
    *,
    temporary_video: Path,
    temporary_lossless_video: Path | None,
    temporary_ass: Path,
    temporary_report: Path,
    preview_script: Path,
    av1_cq: int,
    pronunciation_validation: str = "optional",
    vinyl_motion: str = "rotate",
    lossless_companion: bool = False,
    singer_colors: Sequence[str] = (),
) -> list[str]:
    visual_style = _task_visual_style(task)
    command = [
        sys.executable,
        str(preview_script.resolve()),
        "--sug",
        str(task.sug_path),
        "--audio",
        str(task.track.audio_path),
        "--composition",
        str(task.composition_path),
        "--visual-style",
        visual_style,
        "--fonts-dir",
        str(task.fonts_dir),
        "--font-file",
        str(task.font_file),
        "--output",
        str(temporary_video),
        "--ass-output",
        str(temporary_ass),
        "--report-output",
        str(temporary_report),
        "--start",
        "0",
        "--duration",
        f"{task.duration_seconds:.3f}",
        "--layout",
        task.profile,
        "--video-encoder",
        "av1_nvenc",
        "--av1-cq",
        str(av1_cq),
        "--pronunciation-validation",
        pronunciation_validation,
    ]
    if visual_style == "vinyl":
        if task.vinyl_path is None:
            raise DirectAV1420RenderError("vinyl task has no vinyl asset")
        command.extend(["--vinyl", str(task.vinyl_path), "--vinyl-motion", vinyl_motion])
    command.extend(["--color-policy", "cover"])
    for singer_color in singer_colors:
        command.extend(["--singer-color", singer_color])
    lossless_policy = lossless_companion_policy(
        task.track.audio_path,
        requested=lossless_companion,
    )
    if lossless_policy["status"] == "requested":
        if temporary_lossless_video is None:
            raise DirectAV1420RenderError(
                "lossless FLAC/PCM WAV source requires a companion output path"
            )
        command.extend(["--lossless-output", str(temporary_lossless_video)])
    timing_overrides = _timing_overrides_path(task)
    song_id = getattr(getattr(task, "track", None), "song_id", None)
    if timing_overrides is not None and song_id is not None:
        command.extend(
            [
                "--timing-overrides",
                str(timing_overrides),
                "--song-id",
                str(song_id),
            ]
        )
    return command


def _flag_value(command: Sequence[str], flag: str) -> str:
    try:
        return str(command[command.index(flag) + 1])
    except (ValueError, IndexError) as error:
        raise DirectAV1420RenderError(f"preview command is missing {flag}") from error


def validate_direct_source_command(command: Sequence[str]) -> None:
    if _flag_value(command, "--video-encoder") != "av1_nvenc":
        raise DirectAV1420RenderError("AV1 lane must use video_encoder=av1_nvenc")
    visual_style = (
        _flag_value(command, "--visual-style")
        if "--visual-style" in command
        else "vinyl"
    )
    if visual_style not in {"vinyl", "spectrum"}:
        raise DirectAV1420RenderError(f"unsupported visual style: {visual_style!r}")
    expected_suffixes = {
        "--sug": ".sug",
        "--composition": ".png",
    }
    if visual_style == "vinyl":
        expected_suffixes["--vinyl"] = ".png"
    elif "--vinyl" in command:
        raise DirectAV1420RenderError("spectrum task must not receive --vinyl")
    for flag, suffix in expected_suffixes.items():
        source = Path(_flag_value(command, flag))
        if source.suffix.casefold() != suffix:
            raise DirectAV1420RenderError(
                f"direct AV1 source {flag} must be {suffix}, got {source}"
            )
    audio_source = Path(_flag_value(command, "--audio"))
    has_lossless_output = "--lossless-output" in command
    lossless_companion_policy(audio_source, requested=has_lossless_output)
    if has_lossless_output and Path(
        _flag_value(command, "--lossless-output")
    ).suffix.casefold() != ".mkv":
        raise DirectAV1420RenderError("lossless AV1 output must use Matroska (.mkv)")
    forbidden_video_suffixes = {".mp4", ".mkv", ".mov", ".webm", ".avi", ".m4v"}
    for flag in expected_suffixes:
        source = Path(_flag_value(command, flag))
        if source.suffix.casefold() in forbidden_video_suffixes:
            raise DirectAV1420RenderError(f"video master input is forbidden: {source}")
    if "--timing-overrides" in command:
        timing_overrides = Path(_flag_value(command, "--timing-overrides"))
        if timing_overrides.suffix.casefold() != ".json":
            raise DirectAV1420RenderError(
                f"timing overrides must be JSON: {timing_overrides}"
            )
        _flag_value(command, "--song-id")


