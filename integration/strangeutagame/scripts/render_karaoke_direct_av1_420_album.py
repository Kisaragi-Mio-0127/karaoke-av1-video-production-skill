def _task_visual_style(task: Any) -> str:
    return str(getattr(task, "visual_style", "vinyl"))


class DirectAV1420RenderError(RuntimeError):
    """Raised when an AV1 4:2:0 artifact fails a publication gate."""


def validate_editable_pronunciation_sources(
    tasks: Iterable[render_core.RenderTask],
    *,
    mode: str,
) -> list[dict[str, Any]]:
    """Apply the shared pronunciation policy before starting any encode."""

    checked: set[Path] = set()
    results: list[dict[str, Any]] = []
    for task in tasks:
        path = task.sug_path.resolve()
        if path in checked:
            continue
        checked.add(path)
        document = json.loads(path.read_text(encoding="utf-8"))
        sidecar_path = path.with_suffix(".ruby-review.json")
        sidecar = load_review_sidecar(sidecar_path) if sidecar_path.is_file() else None
        try:
            result = validate_pronunciation(
                document,
                mode=mode,
                sidecar=sidecar,
                sidecar_validator=validate_review_sidecar,
            )
        except (RubyValidationError, ValueError) as error:
            raise DirectAV1420RenderError(
                f"pronunciation validation failed for {path.name}: {error}"
            ) from error
        results.append({"sug": str(path), **result.to_dict()})
    return results


def verify_editable_ruby_sources(tasks: Iterable[render_core.RenderTask]) -> None:
    """Compatibility wrapper for callers that require the strict old gate."""

    validate_editable_pronunciation_sources(tasks, mode="required")


def validate_current_vinyl_assets(
    tasks: Iterable[render_core.RenderTask],
) -> list[dict[str, Any]]:
    """Reject vinyl assets not regenerated by the current artwork workflow."""

    if not VINYL_GENERATOR.is_file():
        raise DirectAV1420RenderError(f"vinyl generator is missing: {VINYL_GENERATOR}")
    generator_hash = sha256_file(VINYL_GENERATOR)
    generator_source = VINYL_GENERATOR.read_text(encoding="utf-8")
    style_match = re.search(
        r"^VINYL_STYLE_VERSION\s*=\s*['\"]([^'\"]+)['\"]",
        generator_source,
        re.MULTILINE,
    )
    if style_match is None:
        raise DirectAV1420RenderError(
            "current vinyl generator does not declare VINYL_STYLE_VERSION; "
            "all existing vinyl assets are stale until generator metadata is available"
        )
    current_style_version = style_match.group(1)
    generator_mtime = VINYL_GENERATOR.stat().st_mtime_ns
    checked: set[Path] = set()
    results: list[dict[str, Any]] = []
    for task in tasks:
        if _task_visual_style(task) != "vinyl":
            continue
        if task.vinyl_path is None:
            raise DirectAV1420RenderError("vinyl task has no vinyl asset")
        vinyl = task.vinyl_path.resolve()
        if vinyl in checked:
            continue
        checked.add(vinyl)
        provenance_path = vinyl.parent / "artwork.json"
        if not provenance_path.is_file():
            raise DirectAV1420RenderError(
                f"vinyl provenance is missing for {vinyl.name}; regenerate artwork"
            )
        try:
            provenance = json.loads(provenance_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise DirectAV1420RenderError(
                f"invalid vinyl provenance {provenance_path}: {error}"
            ) from error
        generated_files = (
            provenance.get("generated_files") if isinstance(provenance, dict) else None
        )
        if not isinstance(generated_files, Mapping) or generated_files.get("vinyl") != vinyl.name:
            raise DirectAV1420RenderError(
                f"vinyl provenance does not identify {vinyl.name}; regenerate artwork"
            )
        metadata_style_version = provenance.get("vinyl_style_version")
        metadata_generator_hash = provenance.get("vinyl_generator_sha256")
        generator_hash_field = "vinyl_generator_sha256"
        if not metadata_generator_hash:
            metadata_generator_hash = provenance.get("render_vinyl_karaoke_sha256")
            generator_hash_field = "render_vinyl_karaoke_sha256"
        metadata_vinyl_hash = provenance.get("vinyl_sha256")
        actual_vinyl_hash = sha256_file(vinyl)
        missing_identity_fields = [
            name
            for name, value in (
                ("vinyl_style_version", metadata_style_version),
                (
                    "vinyl_generator_sha256 (or legacy render_vinyl_karaoke_sha256)",
                    metadata_generator_hash,
                ),
                ("vinyl_sha256", metadata_vinyl_hash),
            )
            if not isinstance(value, str) or not value
        ]
        if missing_identity_fields:
            raise DirectAV1420RenderError(
                f"stale vinyl asset {vinyl.name}; artwork.json is missing "
                f"{', '.join(missing_identity_fields)}; regenerate artwork"
            )
        if metadata_style_version != current_style_version:
            raise DirectAV1420RenderError(
                f"stale vinyl style {metadata_style_version!r} for {vinyl.name}; "
                f"current style is {current_style_version!r}"
            )
        if metadata_generator_hash != generator_hash:
            raise DirectAV1420RenderError(
                f"stale vinyl generator hash for {vinyl.name}; regenerate artwork"
            )
        if metadata_vinyl_hash != actual_vinyl_hash:
            raise DirectAV1420RenderError(
                f"vinyl hash does not match artwork.json for {vinyl.name}"
            )
        mtime_current = (
            vinyl.stat().st_mtime_ns >= generator_mtime
            and provenance_path.stat().st_mtime_ns >= generator_mtime
        )
        results.append(
            {
                "status": "pass",
                "reason": "regenerated-with-current-vinyl-generator",
                "vinyl": str(vinyl),
                "vinyl_sha256": actual_vinyl_hash,
                "vinyl_style_version": current_style_version,
                "provenance": str(provenance_path),
                "provenance_sha256": sha256_file(provenance_path),
                "generated_at_utc": provenance.get("generated_at_utc"),
                "source_sha256": provenance.get("source_sha256"),
                "generator": str(VINYL_GENERATOR),
                "generator_sha256": generator_hash,
                "generator_hash_metadata_field": generator_hash_field,
                "mtime_current": mtime_current,
                "mtime_role": "auxiliary-only",
            }
        )
    return results


def validate_current_wide_compositions(
    tasks: Iterable[render_core.RenderTask],
    *,
    visual_style: str | None = None,
) -> list[dict[str, Any]]:
    """Reject wide compositions built for another style or obsolete layout."""

    sleeve_by_style = {
        "vinyl": {"x": 40, "y": 30, "width": 340, "height": 402},
        "spectrum": {"x": 40, "y": 30, "width": 460, "height": 522},
    }
    title_block_x_by_style = {"vinyl": 430, "spectrum": 800}
    title_block_y = {"label": 120, "title": 155, "artist": 220}
    secondary_safe_bounds = [0, 0, 1920, 96]
    secondary_reserved_bounds = [0, 0, 1920, 107]
    minimum_title_clearance_px = 16
    if not WIDE_ARTWORK_GENERATOR.is_file():
        raise DirectAV1420RenderError(
            f"wide artwork generator is missing: {WIDE_ARTWORK_GENERATOR}"
        )
    generator_hash = sha256_file(WIDE_ARTWORK_GENERATOR)
    generator_source = WIDE_ARTWORK_GENERATOR.read_text(encoding="utf-8")
    version_match = re.search(
        r"^WIDE_LAYOUT_VERSION\s*=\s*['\"]([^'\"]+)['\"]",
        generator_source,
        re.MULTILINE,
    )
    if version_match is None:
        raise DirectAV1420RenderError(
            "wide artwork generator does not declare WIDE_LAYOUT_VERSION"
        )
    current_version = version_match.group(1)
    checked: set[Path] = set()
    results: list[dict[str, Any]] = []
    for task in tasks:
        if task.profile != "wide":
            continue
        task_style = str(getattr(task, "visual_style", "vinyl"))
        if (
            visual_style is not None
            and hasattr(task, "visual_style")
            and task_style != visual_style
        ):
            raise DirectAV1420RenderError(
                f"task visual_style={task_style!r} does not match requested {visual_style!r}"
            )
        current_style = visual_style or task_style
        try:
            expected_sleeve = sleeve_by_style[current_style]
        except KeyError as error:
            raise DirectAV1420RenderError(
                f"unsupported wide visual style: {current_style!r}"
            ) from error
        composition = task.composition_path.resolve()
        if composition in checked:
            continue
        checked.add(composition)
        metadata_path = composition.with_suffix(".json")
        if not metadata_path.is_file():
            raise DirectAV1420RenderError(
                f"wide composition metadata is missing for {composition.name}; "
                "regenerate wide artwork"
            )
        try:
            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as error:
            raise DirectAV1420RenderError(
                f"invalid wide composition metadata {metadata_path}: {error}"
            ) from error
        if not isinstance(metadata, Mapping):
            raise DirectAV1420RenderError(
                f"wide composition metadata must be an object: {metadata_path}"
            )
        actual_hash = sha256_file(composition)
        title_bounds = metadata.get("title_bounds")
        title_bounds_valid = (
            isinstance(title_bounds, list)
            and len(title_bounds) == 4
            and all(isinstance(value, int) for value in title_bounds)
            and title_bounds[0] < title_bounds[2]
            and title_bounds[1] < title_bounds[3]
        )
        overlay_contract = metadata.get("secondary_overlay_contract")
        overlay_contract_valid = (
            isinstance(overlay_contract, Mapping)
            and overlay_contract.get("anchor_y") == 12
            and overlay_contract.get("font_size_px") == 60
            and overlay_contract.get("safe_bounds") == secondary_safe_bounds
            and overlay_contract.get("outline_px") == 3
            and overlay_contract.get("glow_px") == 8
            and overlay_contract.get("reserved_bounds") == secondary_reserved_bounds
        )
        title_clearance = (
            title_bounds[1] - secondary_reserved_bounds[3]
            if title_bounds_valid
            else None
        )
        checks = {
            "layout_version": metadata.get("layout_version") == current_version,
            "layout_generator_sha256": (
                metadata.get("layout_generator_sha256") == generator_hash
            ),
            "composition_sha256": metadata.get("composition_sha256") == actual_hash,
            "visual_style": metadata.get("visual_style") == current_style,
            "sleeve": metadata.get("sleeve") == expected_sleeve,
            "title_block_x": (
                metadata.get("title_block_x") == title_block_x_by_style[current_style]
            ),
            "title_block_y": metadata.get("title_block_y") == title_block_y,
            "title_bounds": title_bounds_valid,
            "secondary_overlay_contract": overlay_contract_valid,
            "secondary_reserved_bounds": (
                metadata.get("secondary_reserved_bounds")
                == secondary_reserved_bounds
            ),
            "title_secondary_no_collision": (
                title_bounds_valid
                and title_clearance >= minimum_title_clearance_px
                and metadata.get("title_secondary_clearance_px") == title_clearance
                and metadata.get("title_secondary_collision") is False
            ),
            "bottom_panel": metadata.get("bottom_panel") == [20, 576, 1900, 1050],
            "outer_right_panel_removed": (
                metadata.get("right_panel") is None
                and metadata.get("right_panel_visible") is False
                and metadata.get("outer_right_panel") is None
                and metadata.get("outer_right_panel_visible") is False
            ),
            "vinyl_backplate_absent": (
                "vinyl_backplate" in metadata
                and metadata.get("vinyl_backplate") is None
                and metadata.get("vinyl_backplate_present") is False
                and metadata.get("vinyl_backplate_preserved") is False
            ),
        }
        failed = [name for name, ok in checks.items() if not ok]
        if failed:
            raise DirectAV1420RenderError(
                f"stale wide composition {composition.name}; failed "
                f"{', '.join(failed)}; regenerate wide artwork"
            )
        results.append(
            {
                "status": "pass",
                "composition": str(composition),
                "composition_sha256": actual_hash,
                "metadata": str(metadata_path),
                "layout_version": current_version,
                "layout_generator_sha256": generator_hash,
                "visual_style": current_style,
                "title_block_x": title_block_x_by_style[current_style],
                "title_block_y": title_block_y,
                "title_bounds": title_bounds,
                "secondary_reserved_bounds": secondary_reserved_bounds,
                "title_secondary_clearance_px": title_clearance,
                "title_secondary_collision": False,
                "right_panel_visible": False,
                "outer_right_panel_visible": False,
                "vinyl_backplate": None,
                "vinyl_backplate_present": False,
                "vinyl_backplate_preserved": False,
                "bottom_panel_y": 576,
            }
        )
    return results


def _resolve_path(value: Path | str) -> Path:
    path = Path(value).expanduser()
    if not path.is_absolute():
        path = REPO_ROOT / path
    return path.resolve()


def _temporary_path(target: Path) -> Path:
    return target.with_name(
        f".{target.stem}.{uuid.uuid4().hex}.partial{target.suffix}"
    )


def _remove_if_present(path: Path) -> None:
    with suppress(FileNotFoundError):
        path.unlink()


def _publish_atomically(
    pairs: Sequence[tuple[Path, Path]],
    *,
    post_publish_check: Callable[[], None] | None = None,
) -> None:
    """Publish a generation as one rollback-safe artifact set."""

    for temporary, _target in pairs:
        if not temporary.is_file():
            raise DirectAV1420RenderError(
                f"validated temporary artifact disappeared: {temporary}"
            )
    token = uuid.uuid4().hex
    states: list[tuple[Path, Path | None]] = []
    try:
        for temporary, target in pairs:
            target.parent.mkdir(parents=True, exist_ok=True)
            backup: Path | None = None
            if target.exists():
                backup = target.with_name(f".{target.name}.{token}.rollback")
                os.replace(str(target), str(backup))
            states.append((target, backup))
            os.replace(str(temporary), str(target))
        if post_publish_check is not None:
            post_publish_check()
    except Exception:
        for target, backup in reversed(states):
            _remove_if_present(target)
            if backup is not None and backup.exists():
                os.replace(str(backup), str(target))
        raise
    else:
        for _target, backup in states:
            if backup is not None:
                _remove_if_present(backup)


def write_json_atomically(path: Path, value: dict[str, Any]) -> None:
    temporary = _temporary_path(path)
    try:
        temporary.parent.mkdir(parents=True, exist_ok=True)
        temporary.write_text(
            json.dumps(value, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        _publish_atomically([(temporary, path)])
    finally:
        _remove_if_present(temporary)


def _timing_overrides_path(task: Any) -> Path | None:
    root = getattr(task, "root", None)
    if root is None:
        return None
    path = Path(root) / "sources" / "timing_overrides.json"
    return path.resolve() if path.is_file() else None


def _source_record(
    task: render_core.RenderTask,
    *,
    ass_path: Path | None = None,
) -> dict[str, str | None]:
    def relative(path: Path | None) -> str | None:
        return project_relative(path, REPO_ROOT) if path is not None else None

    def identity(path: Path | None) -> str | None:
        return sha256_file(path) if path is not None and path.is_file() else None

    timing_overrides = _timing_overrides_path(task)
    published_ass = ass_path or task.ass_output
    visual_style = _task_visual_style(task)
    vinyl_path = task.vinyl_path if visual_style == "vinyl" else None
    if visual_style == "vinyl" and vinyl_path is None:
        raise DirectAV1420RenderError("vinyl task has no vinyl asset")
    vinyl_provenance = vinyl_path.parent / "artwork.json" if vinyl_path else None
    vinyl_metadata: Mapping[str, Any] = {}
    if vinyl_provenance is not None and vinyl_provenance.is_file():
        try:
            candidate = json.loads(vinyl_provenance.read_text(encoding="utf-8"))
            if isinstance(candidate, Mapping):
                vinyl_metadata = candidate
        except (OSError, ValueError):
            pass
    sources: dict[str, str | None] = {
        "audio": relative(task.track.audio_path),
        "audio_sha256": identity(task.track.audio_path),
        "composition": relative(task.composition_path),
        "composition_sha256": identity(task.composition_path),
        "sug": relative(task.sug_path),
        "sug_sha256": identity(task.sug_path),
        # Record the profile ASS destination, not the pre-render discovery
        # candidate.  Once the profile ASS is published, task planning finds
        # that file as ``ass_source``; using the discovery candidate here
        # otherwise makes a freshly rendered report immediately look stale.
        "latest_ass": relative(task.ass_output),
        "latest_ass_sha256": identity(published_ass),
        "timing_overrides": relative(timing_overrides),
        "timing_overrides_sha256": (
            sha256_file(timing_overrides) if timing_overrides is not None else None
        ),
    }
    if vinyl_path is not None:
        sources.update(
            {
                "vinyl": relative(vinyl_path),
                "vinyl_sha256": identity(vinyl_path),
                "vinyl_provenance": relative(vinyl_provenance),
                "vinyl_provenance_sha256": identity(vinyl_provenance),
                "vinyl_generated_at_utc": vinyl_metadata.get("generated_at_utc"),
                "vinyl_source_sha256": vinyl_metadata.get("source_sha256"),
                "vinyl_style_version": vinyl_metadata.get("vinyl_style_version"),
                "vinyl_metadata_sha256": vinyl_metadata.get("vinyl_sha256"),
                "vinyl_metadata_generator_sha256": vinyl_metadata.get(
                    "vinyl_generator_sha256"
                )
                or vinyl_metadata.get("render_vinyl_karaoke_sha256"),
                "vinyl_metadata_generator_sha256_field": (
                    "vinyl_generator_sha256"
                    if vinyl_metadata.get("vinyl_generator_sha256")
                    else "render_vinyl_karaoke_sha256"
                    if vinyl_metadata.get("render_vinyl_karaoke_sha256")
                    else None
                ),
                "vinyl_generator": relative(VINYL_GENERATOR),
                "vinyl_generator_sha256": identity(VINYL_GENERATOR),
            }
        )
    return sources


def _canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _identity_digest(value: Any) -> str:
    return hashlib.sha256(_canonical_json(value).encode("utf-8")).hexdigest()


def _read_sug_document(path: Path) -> dict[str, Any] | None:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError, TypeError):
        return None
    return value if isinstance(value, dict) else None


def _source_ruby_entries(document: Mapping[str, Any] | None) -> list[dict[str, Any]]:
    if document is None:
        return []
    sentences = document.get("sentences")
    if not isinstance(sentences, list):
        return []
    entries: list[dict[str, Any]] = []
    for sentence_index, sentence in enumerate(sentences):
        if not isinstance(sentence, Mapping):
            continue
        characters = sentence.get("characters")
        if not isinstance(characters, list):
            continue
        for character_index, character in enumerate(characters):
            if not isinstance(character, Mapping):
                continue
            ruby = character.get("ruby")
            parts = ruby.get("parts") if isinstance(ruby, Mapping) else None
            if not isinstance(parts, list):
                continue
            reading = "".join(
                str(part.get("text") or "")
                for part in parts
                if isinstance(part, Mapping)
            )
            if not reading:
                continue
            entries.append(
                {
                    "sentence_index": sentence_index,
                    "character_index": character_index,
                    "text": str(character.get("char") or ""),
                    "reading": reading,
                }
            )
    return entries


def _rendered_ruby_entries(report: Mapping[str, Any]) -> list[dict[str, Any]]:
    ass = report.get("ass")
    lines = ass.get("lines") if isinstance(ass, Mapping) else None
    if not isinstance(lines, list):
        return []
    entries: list[dict[str, Any]] = []
    for line_index, line in enumerate(lines):
        if not isinstance(line, Mapping):
            continue
        ruby = line.get("ruby")
        if not isinstance(ruby, list):
            continue
        for ruby_index, token in enumerate(ruby):
            if not isinstance(token, Mapping):
                continue
            text = str(token.get("text") or "")
            reading = str(token.get("reading") or "")
            if not text or not reading:
                continue
            entries.append(
                {
                    "line_index": line_index,
                    "ruby_index": ruby_index,
                    "text": text,
                    "reading": reading,
                }
            )
    return entries


def _language_interface() -> Any:
    """Return the shared language resolver when it is available.

    The fallback remains deterministic and reads the language from SUG
    metadata; it is not a second source of project language policy.
    """

    if callable(_shared_language_identity):
        return _shared_language_identity
    for name in (
        "language_identity",
        "get_language_identity",
        "resolve_language_identity",
    ):
        candidate = getattr(render_core, name, None)
        if callable(candidate):
            return candidate
    return None


def _call_language_interface(
    callback: Any,
    *,
    task: render_core.RenderTask,
    document: Mapping[str, Any] | None,
    fallback_language: Any,
) -> Any:
    try:
        parameters = list(inspect.signature(callback).parameters.values())
    except (TypeError, ValueError):
        parameters = []
    if not parameters:
        return callback()
    parameter = parameters[0]
    name = parameter.name.casefold()
    if callback is _shared_language_identity or "language" in name:
        argument: Any = fallback_language
    elif "path" in name or "sug" in name or "source" in name:
        argument: Any = task.sug_path
    elif "document" in name or "project" in name or "metadata" in name:
        argument = document
    else:
        argument = task
    return callback(argument)


def _normalise_language_identity(
    value: Any,
    *,
    fallback_language: Any = None,
    source: str,
) -> dict[str, Any]:
    if isinstance(value, Mapping):
        payload = dict(value)
        code = next(
            (
                payload.get(key)
                for key in ("code", "language", "language_code", "locale")
                if payload.get(key) not in (None, "")
            ),
            fallback_language,
        )
        identity = payload.get("identity") or payload.get("sha256")
        identity = str(identity) if identity else _identity_digest(payload)
    else:
        code = value if value not in (None, "") else fallback_language
        payload = {"code": code} if code not in (None, "") else {}
        identity = _identity_digest(payload)
    result = {
        "code": str(code) if code not in (None, "") else None,
        "identity": identity,
        "source": source,
    }
    if isinstance(value, Mapping):
        result.update(payload)
        result["code"] = str(code) if code not in (None, "") else None
        result["identity"] = identity
        result["source"] = source
    return result


def language_identity(
    task: render_core.RenderTask,
    report: Mapping[str, Any] | None = None,
    *,
    prefer_report: bool = True,
) -> dict[str, Any]:
    """Resolve language through the shared policy or deterministic SUG metadata."""

    if (
        prefer_report
        and report is not None
        and isinstance(report.get("language_identity"), Mapping)
    ):
        return dict(report["language_identity"])
    document = _read_sug_document(task.sug_path)
    metadata = document.get("metadata") if isinstance(document, Mapping) else None
    fallback_language = (
        metadata.get("language")
        if isinstance(metadata, Mapping)
        else document.get("language") if isinstance(document, Mapping) else None
    )
    callback = _language_interface()
    if callback is not None:
        try:
            value = _call_language_interface(
                callback,
                task=task,
                document=document,
                fallback_language=fallback_language,
            )
        except (OSError, TypeError, KeyError):
            value = None
        if value is not None:
            return _normalise_language_identity(
                value,
                fallback_language=fallback_language,
                source="shared-language-interface",
            )
    return _normalise_language_identity(
        fallback_language,
        fallback_language=fallback_language,
        source="sug-metadata",
    )


def ruby_identity(
    task: render_core.RenderTask,
    report: Mapping[str, Any],
) -> dict[str, Any]:
    """Record source and rendered ruby identities without rewriting either."""

    source_entries = _source_ruby_entries(_read_sug_document(task.sug_path))
    rendered_entries = _rendered_ruby_entries(report)
    source = {
        "identity": _identity_digest(source_entries),
        "count": len(source_entries),
        "available": bool(source_entries),
    }
    rendered = {
        "identity": _identity_digest(rendered_entries),
        "count": len(rendered_entries),
        "available": bool(rendered_entries),
    }
    source_values = [(item["text"], item["reading"]) for item in source_entries]
    rendered_values = [(item["text"], item["reading"]) for item in rendered_entries]
    available = source["available"] or rendered["available"]
    consistent = source_values == rendered_values
    return {
        "status": "pass" if available and consistent else "fail" if available else "not-available",
        "consistent": consistent,
        "identity": _identity_digest(source_values) if consistent else None,
        "source": source,
        "rendered": rendered,
    }


def build_language_ruby_identity(
    task: render_core.RenderTask,
    report: Mapping[str, Any],
) -> dict[str, Any]:
    return {
        "language": language_identity(task, report, prefer_report=False),
        "ruby": ruby_identity(task, report),
    }


def _identity_key(value: Any) -> str | None:
    if value is None:
        return None
    if isinstance(value, Mapping):
        identity = value.get("identity")
        if identity not in (None, ""):
            return str(identity)
    return _canonical_json(value) if isinstance(value, (Mapping, list, tuple)) else str(value)


def aggregate_language_ruby_identity(
    results: Sequence[Mapping[str, Any]],
) -> dict[str, Any]:
    """Aggregate identity by song and reject cross-profile drift."""

    by_song: dict[str, dict[str, Any]] = {}
    incomplete = False
    for item in results:
        song_id = str(item.get("song_id"))
        language = item.get("language_identity", item.get("language"))
        ruby = item.get("ruby_identity", item.get("ruby"))
        if language is None or ruby is None:
            incomplete = True
            continue
        bucket = by_song.setdefault(
            song_id,
            {
                "song_id": song_id,
                "language_identity": language,
                "ruby_identity": ruby,
                "profiles": [],
                "visual_styles": [],
            },
        )
        if _identity_key(bucket["language_identity"]) != _identity_key(language):
            raise DirectAV1420RenderError(
                f"aggregate language identity mismatch for song {song_id}"
            )
        if _identity_key(bucket["ruby_identity"]) != _identity_key(ruby):
            raise DirectAV1420RenderError(
                f"aggregate ruby identity mismatch for song {song_id}"
            )
        profile = str(item.get("profile"))
        visual_style = str(item.get("visual_style", "vinyl"))
        if profile not in bucket["profiles"]:
            bucket["profiles"].append(profile)
        if visual_style not in bucket["visual_styles"]:
            bucket["visual_styles"].append(visual_style)
    if not by_song:
        status = "not-provided"
    elif incomplete:
        status = "incomplete"
    else:
        status = "pass"
    return {
        "status": status,
        "songs": [by_song[key] for key in sorted(by_song)],
    }


def configure_av1_tasks(
    tasks: Iterable[render_core.RenderTask],
    *,
    root: Path,
) -> tuple[render_core.RenderTask, ...]:
    configured: list[render_core.RenderTask] = []
