    if not isinstance(ass, dict):
        ass = {}
        result["ass"] = ass
    ass["ass"] = str(task.ass_output.resolve())
    video = result.setdefault("video", {})
    if not isinstance(video, dict):
        video = {}
        result["video"] = video
    if lossless_policy["status"] == "requested":
        if lossless_media is None or lossless_video_sha256 is None:
            raise DirectAV1420RenderError(
                "lossless companion was requested but validation evidence is missing"
            )
